def get_model(name: str) -> dict:
    key = (name or "gamma").strip().lower()
    if key not in MODELS:
        known = ", ".join(sorted(MODELS))
        raise ValueError(f"Unknown BITAXE_MODEL '{name}'. Use one of: {known}")
    return MODELS[key]
